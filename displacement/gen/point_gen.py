"""Point-defect data generation with GRACE, following the team's recipe (Pyroxene, SIMULATIONS/C15_<A-B>).

Recipe (validated by gen/point_pilot.py + gen/rattle_test.py, RESULTS.md):
  bulk     24-atom C15 cell (Fd-3m, A on 8a, B on 16d) relaxed with FrechetCellFilter (normal strains), FIRE+LBFGS,
           fmax 1e-4; the 3000-atom supercell = the team's MgCu2 template (fractional coordinates, atom ids, types
           of SIMULATIONS/C15_Ag-Be/basefile.data) at our lattice constant (C15 positions have no free parameter)
  defects  the team's 5 cells (replace_id/from/to/wyckoff.txt): 1-1-1-8a (pristine), 1-1-2-8a (antisite 8a),
           1-1--1-8a (vacancy 8a), 9-2-1-16d (antisite 16d), 9-2--1-16d (vacancy 16d); fixed cell; positions
           + Gaussian rattle (sigma 0.02 A) relaxed with FIRE+LBFGS to fmax 1e-4, 2 rattle seeds, lower energy kept
           (breaks symmetric saddles, gen/rattle_test.py); the pristine cell is the relaxed bulk itself
Output, in the team's file format so displacement/build_superset.py reads it unchanged (DISP_SIM_ROOT):
  <out>/SIMULATIONS/C15_<A-B>/{unrelaxed,relaxed}_<key>.{dump,data,dump.yaml}  (dump: id x y z ix iy iz fx fy fz
  c_pe_potential_energy, full precision; yaml: exact total pe), gen.json (bulk, per cell: seeds' energies,
  convergence, steps, time). A compound is skipped when its gen.json exists (resumable).
Compounds: the team's A-site (45) x B-site (28) elements, A/B atomic-radius ratio within the team's 5-95% range
  [1.07, 1.52], minus their compounds and elements without properties; shuffled (seed 0), --part k of --nparts n.

    python -I displacement/gen/point_gen.py list                          (GRACE venv)
    python -I displacement/gen/point_gen.py run <out dir> --part k --nparts n [--compounds A-B,...] [--limit m]
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__)); DISP = os.path.dirname(HERE); CODE = os.path.dirname(DISP)
sys.path.insert(0, HERE)
from point_pilot import POT, SIM, optimise, read_data  # noqa: E402

TEMPLATE = os.path.join(SIM, "C15_Ag-Be", "basefile.data")
CELLS = [(1, 1, 1, "8a"), (1, 1, 2, "8a"), (1, 1, -1, "8a"), (9, 2, 1, "16d"), (9, 2, -1, "16d")]
RATTLE, SEEDS, FMAX = 0.02, (0, 1), 1e-4
EXCLUDED = {"Am", "Bk", "Cm"}
RATIO = (1.07, 1.52)


def team_compounds():
    return sorted(d[4:] for d in os.listdir(SIM) if d.startswith("C15_") and not d.endswith("_MIN"))


def candidates():
    E = json.load(open(os.path.join(CODE, "element_properties.json")))["elements"]
    team = team_compounds()
    As = sorted({c.split("-")[0] for c in team} - EXCLUDED); Bs = sorted({c.split("-")[1] for c in team} - EXCLUDED)
    out = [f"{a}-{b}" for a in As for b in Bs if a != b and a in E and b in E and f"{a}-{b}" not in team
           and RATIO[0] <= E[a]["atomic_radius"] / E[b]["atomic_radius"] <= RATIO[1]]
    rng = np.random.default_rng(0)
    return list(rng.permutation(out))


def template():
    cell, ids, types, pos = read_data(TEMPLATE)
    return ids, types, pos @ np.linalg.inv(cell)  # fractional


def calculator():
    from tensorpotential.calculator import TPCalculator
    return TPCalculator(POT, extra_properties=["atomic_energy"], truncate_extras_by_natoms=True)


def evaluate(at):
    e = at.get_potential_energy(); f = at.get_forces()
    ea = np.asarray(at.calc.results["atomic_energy"], dtype=float).reshape(-1)
    return e, f, ea


def bulk_a(calc, A, B):
    from ase.spacegroup import crystal
    at = crystal([A, B], basis=[(0, 0, 0), (5 / 8, 5 / 8, 5 / 8)], spacegroup=227, cellpar=[34.8116836925 / 5] * 3 + [90] * 3)
    at.calc = calc
    conv, n = optimise(at, FMAX, 3000, cell_mask=[1, 1, 1, 0, 0, 0])
    abc = at.cell.lengths()
    return float(abc.mean()), dict(abc=abc.tolist(), e_atom=at.get_potential_energy() / len(at), conv=conv, steps=n)


def write_dump(path, ids, pos, cell, f, pe):
    L = cell.diagonal()
    with open(path, "w") as fh:
        fh.write(f"ITEM: TIMESTEP\n0\nITEM: NUMBER OF ATOMS\n{len(ids)}\nITEM: BOX BOUNDS xy xz yz pp pp pp\n")
        for k in range(3):
            fh.write(f"0.0 {L[k]:.16e} 0.0\n")
        fh.write("ITEM: ATOMS id x y z ix iy iz fx fy fz c_pe_potential_energy\n")
        for i, p, ff, e in zip(ids, pos, f, pe):
            fh.write(f"{i} {p[0]:.12f} {p[1]:.12f} {p[2]:.12f} 0 0 0 {ff[0]:.10e} {ff[1]:.10e} {ff[2]:.10e} {e:.12f}\n")


def write_data(path, ids, types, pos, cell, masses):
    L = cell.diagonal()
    with open(path, "w") as fh:
        fh.write(f"generated by displacement/gen/point_gen.py (GRACE)\n\n{len(ids)} atoms\n2 atom types\n\n"
                 f"0.0 {L[0]:.16f} xlo xhi\n0.0 {L[1]:.16f} ylo yhi\n0.0 {L[2]:.16f} zlo zhi\n0 0 0 xy xz yz\n\n"
                 f"Masses\n\n1 {masses[0]}\n2 {masses[1]}\n\nAtoms # atomic\n\n")
        for i, t, p in zip(ids, types, pos):
            fh.write(f"{i} {t} {p[0]:.12f} {p[1]:.12f} {p[2]:.12f} 0 0 0\n")


def write_yaml(path, n, pe):
    open(path, "w").write(f"- step: 0\n  atoms: {n}\n  pe: {pe:.15f}\n")


def run_compound(calc, comp, root):
    from ase import Atoms
    from ase.data import atomic_masses, atomic_numbers
    A, B = comp.split("-")
    d = os.path.join(root, "SIMULATIONS", f"C15_{comp}"); os.makedirs(d, exist_ok=True)
    t0 = time.time()
    a, binfo = bulk_a(calc, A, B)
    ids0, types0, frac = template()
    cell = np.eye(3) * 5 * a
    masses = [atomic_masses[atomic_numbers[A]], atomic_masses[atomic_numbers[B]]]
    info = dict(compound=comp, a=a, bulk=binfo, cells={}, recipe=dict(rattle=RATTLE, seeds=SEEDS, fmax=FMAX))
    for did, frm, to, wy in CELLS:
        key = f"{did}-{frm}-{to}-{wy}"
        i0 = int(np.where(ids0 == did)[0][0]); assert types0[i0] == frm
        ids, types = ids0.copy(), types0.copy()
        if to == -1:
            keep = np.arange(len(ids)) != i0
        else:
            keep = np.ones(len(ids), bool); types[i0] = to
        ids, types, pos0 = ids[keep], types[keep], (frac @ cell)[keep]
        at = Atoms(symbols=[(A, B)[t - 1] for t in types], positions=pos0, cell=cell, pbc=True); at.calc = calc
        e0, f0, pe0 = evaluate(at)
        runs = []; best = None
        for s in (SEEDS if frm != to else ()):
            x = at.copy(); x.calc = calc
            r = np.random.default_rng(s).normal(0, RATTLE, x.positions.shape)
            x.positions += r - r.mean(0)  # zero net translation (point labels are not re-centred)
            t = time.time(); conv, n = optimise(x, FMAX, 3000)
            e1, f1, pe1 = evaluate(x)
            runs.append(dict(seed=s, dE=e1 - e0, conv=conv, steps=n, sec=time.time() - t))
            if best is None or e1 < best[0]:
                best = (e1, f1, pe1, x.positions.copy())
        if best is None:  # pristine: the relaxed bulk
            best = (e0, f0, pe0, pos0)
        e1, f1, pe1, pos1 = best
        for tag, p, f, pe, e in (("unrelaxed", pos0, f0, pe0, e0), ("relaxed", pos1, f1, pe1, e1)):
            write_dump(os.path.join(d, f"{tag}_{key}.dump"), ids, p, cell, f, pe)
            write_data(os.path.join(d, f"{tag}_{key}.data"), ids, types, p, cell, masses)
            write_yaml(os.path.join(d, f"{tag}_{key}.dump.yaml"), len(ids), e)
        info["cells"][key] = dict(dE=e1 - e0, runs=runs, natoms=len(ids))
        print(f"  {comp} {key}: dE {e1 - e0:.4f} eV | seeds " +
              " ".join(f"{r['dE']:.4f}{'' if r['conv'] else '(nc)'}" for r in runs) + f" | {time.time() - t0:.0f}s", flush=True)
    write_data(os.path.join(d, "basefile.data"), ids0, types0, frac @ cell, cell, masses)
    info["sec"] = time.time() - t0
    json.dump(info, open(os.path.join(d, "gen.json"), "w"), indent=1)  # written last = done marker
    return info


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("what", choices=["list", "run"]); ap.add_argument("out", nargs="?")
    ap.add_argument("--part", type=int, default=0); ap.add_argument("--nparts", type=int, default=1)
    ap.add_argument("--compounds", default=""); ap.add_argument("--limit", type=int, default=0)
    a = ap.parse_args()
    cs = a.compounds.split(",") if a.compounds else candidates()
    if a.what == "list":
        print(len(cs), "candidate compounds:", " ".join(cs)); return
    cs = cs[a.part:: a.nparts]
    if a.limit:
        cs = cs[: a.limit]
    calc = calculator(); t0 = time.time()
    todo = [c for c in cs if not os.path.isfile(os.path.join(a.out, "SIMULATIONS", f"C15_{c}", "gen.json"))]
    print(f"part {a.part}/{a.nparts}: {len(cs)} compounds, {len(todo)} to do", flush=True)
    for k, c in enumerate(todo):
        try:
            run_compound(calc, c, a.out)
        except Exception as e:  # noqa: BLE001
            print(f"error {c}: {type(e).__name__}: {e}", flush=True); continue
        print(f"compound {k + 1}/{len(todo)} {c} done | {time.time() - t0:.0f}s", flush=True)


if __name__ == "__main__":
    main()
